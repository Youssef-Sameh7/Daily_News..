let featuredArticleId = null;

// =====================================================
// IMAGE URL
// =====================================================

function getImageUrl(item) {

return item.image ||
    fallbackImages[item.category] ||
    fallbackImages.World;

}

// =====================================================
// DISPLAY NEWS
// =====================================================

function displayNews(newsList) {

newsGrid.innerHTML = "";

if (newsList.length === 0) {

    newsGrid.innerHTML = `
        <div class="no-news">
            <h3>No news found</h3>
            <p>Please try another category.</p>
        </div>
    `;

    newsCount.textContent =
        "0 Articles";

    return;
}


newsList.forEach((item, index) => {

    const card =
        document.createElement("article");

    card.className =
        `news-card ${item.imageType || ""}`;

    card.dataset.articleId =
        item.id;

    card.style.animationDelay =
        `${index * 0.04}s`;


    card.innerHTML = `

        <div class="news-image">

            <img
                src="${getImageUrl(item)}"
                alt="${item.title}"
                loading="lazy"
                data-fallback-applied="false"
            >

            <span class="category">
                ${item.category}
            </span>

        </div>


        <div class="news-content">

            <div class="news-meta">
                ${item.date}
            </div>

            <h3>
                ${item.title}
            </h3>

            <p>
                ${item.description}
            </p>

            <button
                class="news-read"
                type="button"
                aria-label="Read ${item.title}"
            >
                Read More →
            </button>

        </div>

    `;


    const readButton =
        card.querySelector(".news-read");


    readButton.addEventListener(
        "click",
        () => openArticle(item.id)
    );


    const image =
        card.querySelector("img");


    image.addEventListener(
        "error",
        () => handleImageError(image, item),
        {
            once: true
        }
    );


    newsGrid.appendChild(card);

});


newsCount.textContent =
    `${newsList.length} Articles`;

}

// =====================================================
// IMAGE ERROR HANDLING
// =====================================================

function handleImageError(image, item) {

if (
    image.dataset.fallbackApplied === "true"
) {
    return;
}


image.dataset.fallbackApplied =
    "true";


image.src =
    fallbackImages[item.category] ||
    fallbackImages.World;

}

// =====================================================
// OPEN ORIGINAL ARTICLE
// =====================================================

function openArticle(id) {

const article =
    news.find(
        (item) => item.id === Number(id)
    );


if (!article) {

    console.error(
        `Article with id ${id} was not found.`
    );

    return;
}


if (
    typeof article.url !== "string" ||
    article.url.trim() === ""
) {

    alert(
        "The original article link is not available."
    );

    return;
}


window.open(
    article.url,
    "_blank",
    "noopener,noreferrer"
);

}

// =====================================================
// FILTER NEWS
// =====================================================

function filterNews(category) {

const buttons =
    document.querySelectorAll(".nav-btn");


buttons.forEach((button) => {

    button.classList.toggle(
        "active",
        button.textContent.trim() === category
    );

});


if (category === "All") {

    displayNews(news);

    sectionTitle.textContent =
        "Latest News";

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

    return;
}


const filtered =
    news.filter(
        (item) =>
            item.category === category
    );


displayNews(filtered);


sectionTitle.textContent =
    `${category} News`;


const newsSection =
    document.querySelector(".news-section");


if (newsSection) {

    window.scrollTo({
        top:
            newsSection.offsetTop - 80,
        behavior: "smooth"
    });

}

}

// =====================================================
// FEATURED NEWS
// =====================================================

function setFeaturedNews(article) {

if (!article) {
    return;
}


featuredArticleId =
    article.id;


featuredTitle.textContent =
    article.title;


featuredDescription.textContent =
    article.description;


featuredImage.src =
    getImageUrl(article);


featuredImage.alt =
    article.title;


featuredImage.dataset.fallbackApplied =
    "false";


featuredImage.className =
    article.imageType || "";


featuredImage.onerror =
    () => {

        if (
            featuredImage.dataset.fallbackApplied === "true"
        ) {
            return;
        }

        featuredImage.dataset.fallbackApplied =
            "true";

        featuredImage.src =
            fallbackImages[article.category] ||
            fallbackImages.World;
    };

}

// =====================================================
// OPEN FEATURED ARTICLE
